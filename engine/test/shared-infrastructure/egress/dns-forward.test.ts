/* The DNS forwarder sends the sandbox uid's allowed lookups to the container's own resolver: the first IPv4 nameserver /etc/resolv.conf names, or a public resolver when it names none. */
import { test } from "node:test";
import assert from "node:assert/strict";
import { firstNameserver } from "../../../src/shared-infrastructure/egress/dns-forward.ts";

test("the upstream is the first IPv4 nameserver the resolver file names, comments and other lines aside", () => {
  assert.equal(firstNameserver("# generated by Docker\nsearch local\nnameserver 127.0.0.11\noptions ndots:0\n"), "127.0.0.11");
  assert.equal(firstNameserver("nameserver 10.0.0.2\nnameserver 10.0.0.3\n"), "10.0.0.2");
  assert.equal(firstNameserver("  nameserver   192.168.1.1  \n"), "192.168.1.1");
});

test("a nameserver that is not an IPv4 address is skipped, and a file with none falls back to a public resolver", () => {
  assert.equal(firstNameserver("nameserver ::1\nnameserver 9.9.9.9\n"), "9.9.9.9");
  assert.equal(firstNameserver("nameserver dns.example.test\n"), "1.1.1.1");
  assert.equal(firstNameserver(""), "1.1.1.1");
});

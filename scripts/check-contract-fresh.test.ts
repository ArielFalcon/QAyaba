import { test } from "node:test";
import assert from "node:assert/strict";
import { findStale, freshnessChecks, pinnedGoGenerator, regenerateGoTypes, regenerateSdkTypes } from "./check-contract-fresh.ts";

test("findStale reports nothing when committed content matches fresh content", () => {
  const stale = findStale([{ label: "x", committedPath: "/fake/x", freshContent: "same" }], () => "same");
  assert.deepEqual(stale, []);
});

test("findStale reports drift when committed content differs from fresh content", () => {
  const stale = findStale(
    [{ label: "contract/openapi.json", committedPath: "/fake/openapi.json", freshContent: "new" }],
    () => "old",
  );
  assert.deepEqual(stale, ["contract/openapi.json: /fake/openapi.json is stale — run `npm run contract:gen && npm run sdk:gen` and commit the result"]);
});

test("findStale reports a missing committed file distinctly from drift", () => {
  const stale = findStale([{ label: "x", committedPath: "/fake/missing", freshContent: "anything" }], () => {
    throw Object.assign(new Error("ENOENT"), { code: "ENOENT" });
  });
  assert.deepEqual(stale, ["x: /fake/missing does not exist — run `npm run contract:gen && npm run sdk:gen` and commit the result"]);
});

test("findStale checks every entry, not just the first", () => {
  const stale = findStale(
    [
      { label: "a", committedPath: "/fake/a", freshContent: "fresh-a" },
      { label: "b", committedPath: "/fake/b", freshContent: "fresh-b" },
    ],
    (path) => (path === "/fake/a" ? "fresh-a" : "stale-b"),
  );
  assert.deepEqual(stale, ["b: /fake/b is stale — run `npm run contract:gen && npm run sdk:gen` and commit the result"]);
});

/* Exercises the real openapi-typescript CLI end-to-end (the actual shell-out this script relies
   on) against a minimal synthetic schema — isolated from the production contract so this test
   doesn't churn every time the real schema changes.
 */
test("regenerateSdkTypes runs the real generator end-to-end on a minimal schema", () => {
  const doc = {
    openapi: "3.0.3",
    info: { title: "fixture", version: "1.0.0" },
    paths: {},
    components: {
      schemas: {
        Widget: { type: "object", properties: { id: { type: "string" } }, required: ["id"] },
      },
    },
  };
  const out = regenerateSdkTypes(JSON.stringify(doc));
  assert.match(out, /auto-generated by openapi-typescript/);
  assert.match(out, /Widget/);
});

const FIXTURE_SCHEMA = JSON.stringify({
  openapi: "3.0.3",
  info: { title: "fixture", version: "1.0.0" },
  paths: { "/widgets": { get: { operationId: "listWidgets", responses: { "200": { description: "ok", content: { "application/json": { schema: { $ref: "#/components/schemas/Widget" } } } } } } } },
  components: { schemas: { Widget: { type: "object", properties: { id: { type: "string" } }, required: ["id"] } } },
});

test("the Go client types are one of the generated artifacts the check holds fresh", () => {
  const checks = freshnessChecks("openapi-json", { sdkTypes: (json) => `sdk of ${json}`, goTypes: (json) => `go of ${json}` });
  assert.deepEqual(checks.map((c) => [c.label, c.freshContent]), [
    ["contract/openapi.json", "openapi-json"],
    ["packages/sdk/src/types.gen.ts", "sdk of openapi-json"],
    ["client/internal/contract/types.gen.go", "go of openapi-json"],
  ]);
});

test("stale Go client types are reported with the command that regenerates them", () => {
  const checks = freshnessChecks("openapi-json", { sdkTypes: () => "sdk", goTypes: () => "fresh go" });
  const stale = findStale(checks, (path) => (path.endsWith("types.gen.go") ? "stale go" : checks.find((c) => c.committedPath === path)!.freshContent));
  assert.equal(stale.length, 1);
  assert.match(stale[0]!, /^client\/internal\/contract\/types\.gen\.go: .* is stale — run `make -C client gen` and commit the result$/);
});

test("the Go generator is the one client/Makefile pins", () => {
  assert.match(pinnedGoGenerator().join(" "), /^go run github\.com\/oapi-codegen\/oapi-codegen\/v2\/cmd\/oapi-codegen@v\d+\.\d+\.\d+$/);
});

test("regenerateGoTypes runs the pinned Go generator end-to-end on a minimal schema", () => {
  const out = regenerateGoTypes(FIXTURE_SCHEMA);
  assert.match(out, /^\/\/ Package contract provides/m);
  assert.match(out, /type Widget struct/);
});
